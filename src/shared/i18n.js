  const LANGS = ['zh-TW', 'zh-CN', 'en'];
  let lang = 'zh-TW';
  function setLang(l) { lang = LANGS.includes(l) ? l : 'zh-TW'; }
  function getLang() { return lang; }
  const has = (o, k) => Object.prototype.hasOwnProperty.call(o, k);
  function t(key, vars) {
    let s = lang === 'en' && has(EN, key) ? EN[key] : lang === 'zh-CN' && has(CN, key) ? CN[key] : key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
    return s;
  }
  // 系統語言 → 介面語言：繁體中文（台灣、香港、澳門、Hant）→ 繁中；簡體中文（大陸、新加坡、Hans、單純 zh）→ 簡中；其他一律英文
  function pickLang(setting, systemLangs) {
    if (LANGS.includes(setting)) return setting;
    const first = String((systemLangs || [])[0] || '').toLowerCase();
    if (/^zh[-_](hant|tw|hk|mo)/.test(first)) return 'zh-TW';
    if (/^zh([-_](hans|cn|sg)|$)/.test(first)) return 'zh-CN';
    return 'en';
  }

  const api = { t, setLang, getLang, pickLang, EN, CN, LANGS };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.I18n = api;
